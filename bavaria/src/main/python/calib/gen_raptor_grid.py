"""Regenerate raptor_grid.json - sensitivity of the PT router weights.

WHY: the eqasim:raptor weights in munich1pct_config.xml are numerically identical
to the OLD mode-choice parameters (in-vehicle -2.162021 u/h = -0.03603 u/min, the
old pt.betaInVehicleTime_u_min; waiting -24.67436 u/h = -0.41124, the old
betaWaitingTime_u_min; walk -4.172657 u/h = -0.06954, the old walk beta). Someone
deliberately synchronised the route search with the choice function. The move to
Table 2 plus calibration broke that synchronisation - the config was never
updated.

WHAT MATTERS: route choice is a shortest-path on generalised cost, so only the
RATIOS between the weights matter, not their absolute level. The decisive one is

    waiting : in-vehicle      router 11.4   vs   choice model 3.4

The router avoids waiting three times more strongly than the choice function
justifies, and undervalues in-vehicle time by 1.67x. It therefore prefers long
one-seat rides - which is a candidate explanation for the pt trip length error
(13.47 km against an 8 km reference) that we "fixed" with a 12-standard-error
shift of the choice beta.

NOTE the ratio moves with the choice beta: reverting pt to the estimated -0.0126
would put the aligned ratio at 16.3, i.e. LONGER trips, not shorter. Alignment
helps only because the calibrated beta is strong. That is why the ratio is swept
here as its own dimension rather than just "aligned vs not".

Run: python gen_raptor_grid.py
"""
import json
from pathlib import Path

OUT = Path(__file__).with_name("raptor_grid.json")

RAPTOR = "--config:eqasim:raptor."
TRAVEL_TIME_KEYS = ["travelTimeRail_u_h", "travelTimeSubway_u_h", "travelTimeBus_u_h",
                    "travelTimeTram_u_h", "travelTimeOther_u_h"]

# Current config (= old mode-choice parameters), u/h
CFG_NOW = {"travel": -2.162021, "wait": -24.67436, "walk": -4.172657, "transfer": -0.5441109}

# Current mode-choice parameters, u/min -> u/h
CHOICE = {"travel": -0.06 * 60, "wait": -0.2054 * 60, "walk": -0.0786 * 60, "transfer": -0.6149}

# In-vehicle is held at the choice value throughout; only ratios drive routing.
IVT = CHOICE["travel"]           # -3.6 u/h
RATIO_NOW = CFG_NOW["wait"] / CFG_NOW["travel"]        # 11.41
RATIO_ALIGNED = CHOICE["wait"] / CHOICE["travel"]      # 3.42


def raptor_args(travel=None, wait=None, walk=None, transfer=None):
    travel = IVT if travel is None else travel
    wait = CHOICE["wait"] if wait is None else wait
    walk = CHOICE["walk"] if walk is None else walk
    transfer = CHOICE["transfer"] if transfer is None else transfer

    args = []
    for k in TRAVEL_TIME_KEYS:
        args += [f"{RAPTOR}{k}", f"{travel:.4f}"]
    args += [f"{RAPTOR}waitTime_u_h", f"{wait:.4f}"]
    args += [f"{RAPTOR}walkTime_u_h", f"{walk:.4f}"]
    args += [f"{RAPTOR}perTransfer_u", f"{transfer:.4f}"]
    return args


def build_runs():
    runs = []

    # Exact current config, as the reference point.
    runs.append({
        "name": "REF_config_as_is",
        "parameters": {},
        "extra_args": raptor_args(travel=CFG_NOW["travel"], wait=CFG_NOW["wait"],
                                  walk=CFG_NOW["walk"], transfer=CFG_NOW["transfer"]),
    })

    # A: the waiting:in-vehicle ratio, everything else aligned.
    for ratio in [11.4, 8.0, 5.5, RATIO_ALIGNED, 2.5]:
        runs.append({
            "name": f"A_ratio{ratio:.1f}",
            "parameters": {},
            "extra_args": raptor_args(wait=IVT * ratio),
        })

    # B: does the choice beta still need its correction once the router is aligned?
    # The raptor in-vehicle weight follows the choice beta, keeping them synchronised.
    for beta in [-0.0126, -0.03, -0.045]:
        runs.append({
            "name": f"B_ptbeta{beta}",
            "parameters": {"pt.betaInVehicleTime_u_min": beta},
            "extra_args": raptor_args(travel=beta * 60, wait=CHOICE["wait"]),
        })

    # C: isolate the two smaller divergences, at the aligned ratio.
    runs.append({
        "name": "C_walk_as_is",
        "parameters": {},
        "extra_args": raptor_args(walk=CFG_NOW["walk"]),
    })
    runs.append({
        "name": "C_transfer_as_is",
        "parameters": {},
        "extra_args": raptor_args(transfer=CFG_NOW["transfer"]),
    })

    return runs


def main():
    runs = build_runs()

    spec = {
        "_comment": [
            f"Raptor router sensitivity. {len(runs)} runs.",
            "GENERATED by gen_raptor_grid.py - regenerate, do not hand-edit.",
            "",
            "The eqasim:raptor weights in the config are numerically identical to the",
            "OLD mode-choice parameters - the route search was deliberately",
            "synchronised with the choice function, and the move to Table 2 plus",
            "calibration broke that. This round asks whether the stale router is the",
            "real cause of the pt trip length error.",
            "",
            "ONLY RATIOS MATTER for route choice (shortest path on generalised cost),",
            "so in-vehicle is held at the choice value and the ratio is swept.",
            f"  router today:   waiting:in-vehicle = {RATIO_NOW:.1f}",
            f"  choice model:   waiting:in-vehicle = {RATIO_ALIGNED:.1f}",
            "",
            "REF_config_as_is  the config exactly as it is now - the reference. Should",
            "                  reproduce the stage-4 result.",
            "A_ratio*          the waiting:in-vehicle ratio from 11.4 (status quo) down",
            "                  to 2.5. A lower ratio makes the router accept waiting in",
            "                  exchange for shorter rides, so pt trips should shorten.",
            "                  This is the main dimension.",
            "B_ptbeta*         with the router kept synchronised to the choice beta,",
            "                  does the beta still need its correction? CAREFUL: the",
            "                  ratio moves with the beta - at the estimated -0.0126 the",
            "                  aligned ratio is 16.3, i.e. LONGER trips. These runs hold",
            "                  waiting fixed and move only in-vehicle, so the ratio",
            "                  rises as the beta weakens. That is the honest test.",
            "C_*               the two smaller divergences (walk 1.93 vs 1.31 relative",
            "                  to in-vehicle, transfer 15.1 vs 10.2 minute-equivalents)",
            "                  held at their current values, everything else aligned.",
            "",
            "WHAT TO MEASURE: pt median trip length per zone is the target quantity -",
            "the share is secondary here. Also worth checking eqasim_pt.csv for the",
            "split between rail / subway / tram / bus: if the router is picking long",
            "rail rides, that is where it shows.",
            "",
            "SYNTAX NOTE: the eqasim:raptor module is set through --config:, which",
            "MATSim parses by stripping 'config:' and splitting at the FIRST dot, so",
            "the colon in the module name is not a problem. Worth confirming with a",
            "single --run-index 0 before launching the whole set.",
        ],
        "base": {
            "car.alpha_u": 0.0,
            "walk.alpha_u": 0.0267,
            "bike.alpha_u": -1.1293,
            "bavariaCarPassenger.alpha_u": -1.3259,
            "pt.alpha_u": 0.8452,
            "bavariaCarPassenger.betaInVehicleTravelTime_u_min": -0.13,
            "pt.betaInVehicleTime_u_min": -0.06,
        },
        "extra_args": ["--use-vdf", "true"],
        "runs": runs,
    }

    OUT.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name} with {len(runs)} runs\n")
    print(f"ratio today {RATIO_NOW:.2f}   aligned {RATIO_ALIGNED:.2f}\n")
    for r in runs:
        ea = r["extra_args"]
        d = {ea[i].replace(RAPTOR, ""): ea[i + 1] for i in range(0, len(ea), 2)}
        ivt = float(d["travelTimeRail_u_h"])
        wait = float(d["waitTime_u_h"])
        beta = r["parameters"].get("pt.betaInVehicleTime_u_min", -0.06)
        print(f"{r['name']:20} ivt {ivt:8.4f}  wait {wait:9.4f}  walk {d['walkTime_u_h']:>8}"
              f"  transf {d['perTransfer_u']:>8}  ratio {wait / ivt:5.1f}  pt_beta {beta}")


if __name__ == "__main__":
    main()
