"""Regenerate asc_grid_final.json - verification run closing the calibration.

Stage 4 converged: mvv shares landed within 0.08 pp on every mode, share_mae
0.956 pp, dist_mae 0.945 km, and the remaining ASC solve was numerically zero
(deltas of -0.002 to -0.012). Everything still wrong is zonal - munich pt +3.50,
umland pt -2.24 - which four global constants cannot fix by construction.

The one open choice is bicycle's travel-time beta. Its length error sits at
+1.11 km, and stage 4 measured what the beta costs in share AT THIS CENTRE:

    beta -0.0995 -> -0.11 :  walk +0.42  bike -1.58  cp +0.33  car +0.17  pt +0.67
    beta -0.0995 -> -0.12 :  walk +0.78  bike -2.92  cp +0.59  car +0.31  pt +1.24

Stage 4's compensated attempt used a stage-1 effect scaled by the share ratio
and overshot bicycle's ASC by ~0.16 u, landing at 14.23% instead of 15 - yet it
still reached dist_mae 0.753, the best of the round. With the effect now
measured directly, the exact compensation follows from the stage-4 gradient, so
this should keep the shares on target AND improve the lengths.

Both ladder steps are included: they run in parallel, so the second costs no
wall-clock time and is the fallback if -0.12 overshoots.

Run: python gen_final_grid.py
"""
import json
from pathlib import Path

import numpy as np

OUT = Path(__file__).with_name("asc_grid_final.json")

SWEPT = ["walk.alpha_u", "bike.alpha_u", "bavariaCarPassenger.alpha_u", "pt.alpha_u"]

# Stage-4 centre: shares on target to within 0.08 pp.
CENTRE = {
    "walk.alpha_u": 0.0267,
    "bike.alpha_u": -1.1293,
    "bavariaCarPassenger.alpha_u": -1.3259,
    "pt.alpha_u": 0.8452,
}

# Betas carried through from stage 3.
BETAS = {
    "bavariaCarPassenger.betaInVehicleTravelTime_u_min": -0.13,
    "pt.betaInVehicleTime_u_min": -0.06,
}

# d(share)/d(alpha) measured at the stage-4 centre (pp per utility, mvv).
J = np.array([
    [9.61, -5.19, -1.69, -0.59],
    [-5.23, 11.36, -1.97, -2.75],
    [-1.51, -1.94, 7.58, -0.66],
    [-2.29, -1.53, -3.24, -1.97],
    [-0.58, -2.70, -0.69, 5.97],
])

# Share effect of the bike beta, measured at the stage-4 centre (pp, mvv).
BIKE_EFFECT = {
    -0.11: np.array([0.42, -1.58, 0.33, 0.17, 0.67]),
    -0.12: np.array([0.78, -2.92, 0.59, 0.31, 1.24]),
}


def compensated(beta):
    """ASCs that undo exactly the share shift this beta causes."""
    delta, *_ = np.linalg.lstsq(J, -BIKE_EFFECT[beta], rcond=None)
    p = {**BETAS, "bike.betaTravelTime_u_min": beta}
    for key, d in zip(SWEPT, delta):
        p[key] = round(CENTRE[key] + d, 4)
    return p


def build_runs():
    return [{"name": f"V_bike{b}", "parameters": compensated(b)} for b in [-0.12, -0.11]]


def main():
    runs = build_runs()

    spec = {
        "_comment": [
            f"FINAL verification. {len(runs)} runs.",
            "GENERATED by gen_final_grid.py - regenerate, do not hand-edit.",
            "",
            "Stage 4 converged: mvv shares within 0.08 pp on every mode, share_mae",
            "0.956 pp, dist_mae 0.945 km, remaining ASC solve numerically zero.",
            "What is left is zonal (munich pt +3.50, umland pt -2.24) and cannot be",
            "fixed by four global constants - that would need zone-specific ASCs,",
            "which is a model extension, not a calibration step.",
            "",
            "The single open choice is bicycle's beta. Its length error is +1.11 km,",
            "and stage 4 measured the share cost of changing it at this exact centre.",
            "The ASCs here undo that shift exactly, solved through the stage-4",
            "gradient - unlike stage 4's own attempt, which scaled a stage-1",
            "measurement by the share ratio and overshot bicycle's ASC by ~0.16 u.",
            "",
            "ACCEPTANCE: the shares should stay on target (mvv errors under ~0.2 pp)",
            "while dist_mae drops below the 0.945 km of the stage-4 centre. If both",
            "hold, this is the final parameter set. If the shares drift instead, the",
            "stage-4 centre is the answer and bicycle's length error stays - it is",
            "1.1 km against a MiD reference rounded to whole kilometres.",
            "",
            "-0.11 is the fallback if -0.12 overshoots the length. It runs in",
            "parallel, so it costs no wall-clock time.",
            "",
            "VoT check: bicycle at -0.12 is 33 EUR/h against the 27.4 of Table 2 as",
            "estimated - at the upper end but defensible. At -0.11 it is 30 EUR/h.",
            "",
            "NOT changed, and still open before the DRT scenarios:",
            "  - DrtPredictor feeds the SLA routing bound into the utility instead of",
            "    the simulated waiting time",
            "  - pt waiting for season-ticket holders is positive",
            "    (-0.2054 + 0.2615 = +0.0561), active for 23.7% of persons",
        ],
        "base": {"car.alpha_u": 0.0, **CENTRE, **BETAS},
        "extra_args": ["--use-vdf", "true"],
        "runs": runs,
    }

    OUT.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name} with {len(runs)} runs\n")
    for r in runs:
        p = r["parameters"]
        print(f"{r['name']}")
        for k in SWEPT:
            print(f"    {k:34} {CENTRE[k]:+.4f} -> {p[k]:+.4f}")
        print(f"    {'bike.betaTravelTime_u_min':34} -0.0995 -> {p['bike.betaTravelTime_u_min']}")
        print(f"    (cp beta {BETAS['bavariaCarPassenger.betaInVehicleTravelTime_u_min']}, "
              f"pt beta {BETAS['pt.betaInVehicleTime_u_min']} unchanged)\n")


if __name__ == "__main__":
    main()
