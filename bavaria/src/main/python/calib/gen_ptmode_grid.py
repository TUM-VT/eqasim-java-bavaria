"""Regenerate ptmode_grid.json - PT sub-mode split via the router weights.

THE PROBLEM (measured on the raptor round):

    U-Bahn      32.8 %  against  59.9 %   -27.1 pp
    Bus total   50.7 %  against  26.8 %   +23.9 pp

That is by far the largest remaining error in the model - the main modal split
sits below 1 pp.

THE CAUSE: all five travelTime*_u_h in munich1pct_config.xml are set to the same
value (-2.162021), so the router is indifferent between 20 minutes of bus and 20
minutes of U-Bahn and decides purely on time and transfers. Buses serve a denser
network, so they win systematically - the more so because the current transfer
aversion is extreme (72 in-vehicle minutes per transfer), and using the U-Bahn
usually requires exactly the transfer the router is avoiding.

EVIDENCE: across the raptor round the U-Bahn share rises monotonically as the
waiting:in-vehicle ratio falls - 27.4 % at ratio 16.3, 37.8 % at ratio 2.5. The
mechanism is confirmed, but even the best case leaves 22 pp missing, so the
ratio alone is not enough. The missing sub-mode differentiation is the main part.

PARAMETERISATION: subway and rail are the anchor (kept at the current -2.162021),
bus/other and tram are penalised by a factor k. The waiting weight is expressed
as a multiple of the anchor, so "ratio" keeps meaning "waiting costs this many
minutes of U-Bahn time". Absolute level is held fixed across runs, which matters:
the raptor round's control pair showed that equal ratios at different absolute
levels do NOT give the same result.

walk and transfer stay at their current values - the raptor round showed they
barely move anything (0.21 km and 0.00 km respectively).

Run: python gen_ptmode_grid.py
"""
import json
from pathlib import Path

OUT = Path(__file__).with_name("ptmode_grid.json")

RAPTOR = "--config:eqasim:raptor."

# Current config values.
ANCHOR = -2.162021          # subway + rail, held fixed
WALK_NOW = -4.172657
TRANSFER_NOW = -0.5441109
WAIT_NOW = -24.67436
RATIO_NOW = WAIT_NOW / ANCHOR     # 11.41

# k = penalty factor on bus/other/tram relative to subway/rail.
# 1.0 is the current uniform setting; 2.8 is roughly the eqasim IdF default
# (bus -2.847 against subway -1.0).
K_VALUES = [1.0, 1.5, 2.0, 2.8]
RATIOS = [RATIO_NOW, 5.5, 3.4]


def raptor_args(k_bus, k_tram, ratio, walk=WALK_NOW, transfer=TRANSFER_NOW):
    args = []
    for key, factor in [("travelTimeSubway_u_h", 1.0), ("travelTimeRail_u_h", 1.0),
                        ("travelTimeBus_u_h", k_bus), ("travelTimeOther_u_h", k_bus),
                        ("travelTimeTram_u_h", k_tram)]:
        args += [f"{RAPTOR}{key}", f"{ANCHOR * factor:.4f}"]
    args += [f"{RAPTOR}waitTime_u_h", f"{ANCHOR * ratio:.4f}"]
    args += [f"{RAPTOR}walkTime_u_h", f"{walk:.4f}"]
    args += [f"{RAPTOR}perTransfer_u", f"{transfer:.4f}"]
    return args


def build_runs():
    runs = [{
        "name": "REF_config_as_is",
        "parameters": {},
        "extra_args": raptor_args(1.0, 1.0, RATIO_NOW),
    }]

    for k in K_VALUES:
        for ratio in RATIOS:
            if k == 1.0 and abs(ratio - RATIO_NOW) < 0.01:
                continue          # identical to REF
            runs.append({
                "name": f"G_k{k}_r{ratio:.1f}",
                "parameters": {},
                "extra_args": raptor_args(k, k, ratio),
            })

    # Separate bus from tram at a mid cell: tram is only +3.1 pp off while bus is
    # +23.9, so penalising both equally may push tram too low.
    runs.append({
        "name": "T_bus_only_k2.0_r5.5",
        "parameters": {},
        "extra_args": raptor_args(2.0, 1.0, 5.5),
    })
    runs.append({
        "name": "T_tram_only_k2.0_r5.5",
        "parameters": {},
        "extra_args": raptor_args(1.0, 2.0, 5.5),
    })

    return runs


def main():
    runs = build_runs()

    spec = {
        "_comment": [
            f"PT sub-mode split via the router weights. {len(runs)} runs.",
            "GENERATED by gen_ptmode_grid.py - regenerate, do not hand-edit.",
            "",
            "Measured on the raptor round: U-Bahn 32.8 % against 59.9 %, bus total",
            "50.7 % against 26.8 %. The largest remaining error in the model.",
            "",
            "Cause: all five travelTime*_u_h are at the same value, so the router",
            "cannot distinguish 20 min of bus from 20 min of U-Bahn. Buses serve a",
            "denser network and win on time plus transfer avoidance.",
            "",
            "G_k*_r*   k penalises bus/other/tram relative to subway/rail (k=1.0 is",
            "          the current uniform setting, k=2.8 is roughly the eqasim IdF",
            "          default). r is waiting expressed in multiples of a U-Bahn",
            "          minute. Both dimensions push the U-Bahn share the same way,",
            "          which is why they are crossed rather than swept separately.",
            "T_*       bus and tram separated at k=2.0 / r=5.5. Tram is only +3.1 pp",
            "          off against bus at +23.9, so an equal penalty may push tram",
            "          below target - these two say which of them carries the effect.",
            "",
            "JUDGE PRIMARILY ON THE CROSS-SECTION COUNTS (compare_run / COUNT_SETS",
            "for ubahn and tram), not on the modal split: the counts are the direct",
            "measurement of the assignment. The MVG split, pt trip length and",
            "share_mae are the secondary criteria - and note they now conflict,",
            "since a lower ratio improves U-Bahn and trip length but worsened",
            "share_mae from 0.956 to 1.750 in the raptor round.",
            "",
            "walk and transfer are held at the current values: the raptor round",
            "showed they move the result by 0.21 km and 0.00 km respectively.",
            "",
            "Absolute level is held fixed on purpose. The raptor round's control",
            "pair (REF_config_as_is vs A_ratio11.4) showed that the same ratio at a",
            "different absolute level gives different results - 0.77 km of pt length",
            "and 2.4 pp of pt share - so the level cannot be varied casually.",
        ],
        "base": {
            "car.alpha_u": 0.0,
            "walk.alpha_u": 0.0267,
            "bike.alpha_u": -1.1293,
            "bavariaCarPassenger.alpha_u": -1.3259,
            "pt.alpha_u": 0.8452,
            "bavariaCarPassenger.betaInVehicleTravelTime_u_min": -0.13,
            "pt.betaInVehicleTime_u_min": -0.06,
        },
        "extra_args": ["--use-vdf", "true"],
        "runs": runs,
    }

    OUT.write_text(json.dumps(spec, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name} with {len(runs)} runs\n")
    print(f"anchor (subway/rail) {ANCHOR}   current ratio {RATIO_NOW:.2f}\n")
    print(f"{'run':24} {'subway':>9} {'bus':>9} {'tram':>9} {'wait':>10} {'ratio':>6}")
    for r in runs:
        ea = r["extra_args"]
        d = {ea[i].replace(RAPTOR, ""): float(ea[i + 1]) for i in range(0, len(ea), 2)}
        print(f"{r['name']:24} {d['travelTimeSubway_u_h']:>9.4f} {d['travelTimeBus_u_h']:>9.4f} "
              f"{d['travelTimeTram_u_h']:>9.4f} {d['waitTime_u_h']:>10.4f} "
              f"{d['waitTime_u_h'] / d['travelTimeSubway_u_h']:>6.1f}")


if __name__ == "__main__":
    main()
